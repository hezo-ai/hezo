-- Model pricing: single source = pricepertoken.com.
--
-- The old refresh merged two public feeds (LiteLLM + llm-prices.com) into
-- 'litellm' rows and seeded from a committed snapshot. Both are replaced by
-- the pricepertoken.com MCP catalog ('pricepertoken' rows, refreshed at boot
-- and daily by the job manager). This migration:
--
--   1. Drops the old feed rows. They are a re-derivable cache of a public
--      feed, not user data; operator 'manual' overrides are preserved.
--   2. Retags the source domain: CHECK + default move from 'litellm' to
--      'pricepertoken'.
--   3. Bakes in the catalog captured at authoring time (generated through the
--      same parse/derive code the live refresh uses), so an instance has
--      correct prices immediately — even before its first successful fetch.
--      The boot/daily refresh then upserts current values over these rows.
--
-- The catalog carries no cache-read/creation rates (columns stay NULL), so
-- the cost math bills cache traffic at the full input rate — a conservative
-- upper-bound estimate. A 'manual' override can set cache rates per model.

